export function getMenuTemplateBySegment(segment: string): any[] {
  const s = (segment || "").toLowerCase().trim();
  if (s.includes("pastel") || s.includes("salgado")) {
    return PASTELARIA_MENU_TEMPLATE;
  }
  if (s.includes("espet") || s.includes("churrasco")) {
    return ESPETINHO_MENU_TEMPLATE;
  }
  if (s.includes("hamburg") || s.includes("burger")) {
    return HAMBURGUERIA_MENU_TEMPLATE;
  }
  if (s.includes("açaí") || s.includes("acai") || s.includes("sorvet")) {
    return ACAI_MENU_TEMPLATE;
  }
  // Default to Pastelaria as requested if matching pastelaria or general
  return PASTELARIA_MENU_TEMPLATE;
}
